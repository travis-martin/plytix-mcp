// Fixture browser check. Start scripts/workspace-preview.mjs after npm run build.
// Set PLAYWRIGHT_MODULE to an installed Playwright module path when it is not on Node's module path.
import { pathToFileURL } from 'node:url';
import { resolve, isAbsolute } from 'node:path';
const modulePath = process.env.PLAYWRIGHT_MODULE ?? 'playwright';
const { chromium } = await import(isAbsolute(modulePath) ? pathToFileURL(modulePath).href : modulePath);
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const directory = resolve(process.env.WORKSPACE_REVIEW_OUTPUT_DIR ?? '.local/workspace-review');
await mkdir(directory, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
try {
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(`${message.text()} ${message.location().url}`); });
const results = [];
const check = (name, condition) => { assert.ok(condition, name); results.push({ name, passed: true }); };
await page.goto(process.env.WORKSPACE_PREVIEW_URL ?? 'http://127.0.0.1:4174/');
const frame = page.frameLocator('#workspace');
await frame.locator('#status').filter({ hasText: 'Ready.' }).waitFor();
await page.evaluate(() => window.fixtureOpenReview());
await frame.getByRole('heading', { name: 'Fixture supplier · sheet price review', exact: true }).waitFor();
check('Host tool result opens the requested saved review', await frame.locator('#tab-pricing').getAttribute('aria-selected') === 'true');
await frame.getByRole('tab', { name: 'Price lists', exact: true }).click();
await frame.locator('#review-id').fill('33333333-3333-4333-8333-333333333333');
await frame.getByRole('button', { name: 'Open review', exact: true }).click();
await frame.getByRole('heading', { name: 'Fixture supplier · sheet price review', exact: true }).waitFor();
check('Page identity', await page.title() === 'Plytix fixture preview');
check('Every line is visible', await frame.locator('.review-table > tbody > tr').count() === 6);
check('Pending totals remain visible', (await frame.locator('#review-progress').innerText()).includes('4 lines still need'));
const row = id => frame.locator(`tr[data-line-id="line-${id}"]`);
check('Original source cell is visible', (await row('A').innerText()).includes('Source cell: Price') && (await row('A').innerText()).includes('Fixture supplier price list.pdf'));
const batchCheck = async ids => { for (const id of ids) await row(id).locator('input[type=checkbox]').check(); };
await batchCheck(['A', 'B']);
await frame.locator('#review-select-approval').click();
await row('A').getByText('Selected for approval', { exact: true }).waitFor();
check('Batch selection is durable', (await frame.locator('#review-ready-count').innerText()) === '2 selected for approval');
await row('A').getByRole('button', { name: 'Modify / instruct', exact: true }).click();
await frame.locator('#review-edit-value').fill('13.25');
await frame.locator('#review-edit-note').fill('Reviewed full-sheet amount. Keep the overridden child unchanged.');
await frame.getByRole('button', { name: 'Save revision request', exact: true }).click();
await row('A').getByText('Needs revision', { exact: true }).waitFor();
check('Modification removes selected status', (await frame.locator('#review-ready-count').innerText()) === '1 selected for approval');
check('Requested amount distinct from calculated amount', (await row('A').innerText()).includes('Requested revision') && (await row('A').innerText()).includes('13.25'));
await batchCheck(['A', 'D']);
await frame.locator('#review-send-instructions').click();
await frame.locator('#review-instruction-status').filter({ hasText: 'Instructions for 2 lines sent' }).waitFor();
const instructionMessage = (await page.evaluate(() => window.fixtureMessage)).content[0].text;
const instructionRequest = JSON.parse(instructionMessage.slice(instructionMessage.indexOf('\n{') + 1));
check('Saved batch instructions request current-review follow-through', instructionMessage.includes('Fetch the current pricing review') && instructionMessage.includes('not approval') && instructionRequest.line_ids.join(',') === 'line-A,line-D');
check('Instruction handoff sends references without copying source or note data', Object.keys(instructionRequest).sort().join(',') === 'expected_revision,line_ids,review_id' && !instructionMessage.includes('Keep the overridden child unchanged.'));
check('Sending instructions leaves decisions unchanged', (await row('A').innerText()).includes('Needs revision') && (await row('D').innerText()).includes('Needs revision'));
await row('A').getByRole('button', { name: 'Recalculate', exact: true }).click();
await row('A').getByText('Pending review', { exact: true }).waitFor();
check('Recalculation requires a new decision', !(await row('A').innerText()).includes('Selected for approval'));
check('Source calculation stays distinct from revised amount', (await row('A').innerText()).includes('Calculated from source') && (await row('A').innerText()).includes('12.50') && (await row('A').innerText()).includes('13.25'));
await row('A').locator('summary').filter({ hasText: '2 descendants' }).click();
check('Inherited effects preserve child overrides', (await row('A').locator('.line-evidence').innerText()).includes('CHILD-OVERRIDE') && (await row('A').locator('.line-evidence').innerText()).includes('14.00'));
await batchCheck(['A', 'B']);
await frame.locator('#review-select-approval').click();
await frame.locator('#review-ready-count').filter({ hasText: '2 selected for approval' }).waitFor();
await frame.locator('#review-filter').selectOption('blocked');
check('Filtering does not hide unresolved totals', (await frame.locator('#review-progress').innerText()).includes('2 lines still need'));
await batchCheck(['C']);
check('Blocked line cannot be selected for approval', await frame.locator('#review-select-approval').isDisabled());
await row('C').locator('input[type=checkbox]').uncheck();
await frame.locator('#review-filter').selectOption('all');
await batchCheck(['A']);
await frame.locator('#review-prepare-checked').click();
await frame.getByRole('heading', { name: 'Prepared for final approval', exact: true }).waitFor();
check('A checked subset can prepare without deselecting other lines', (await frame.locator('#review-prepared').innerText()).includes('1 exact change') && (await frame.locator('#review-ready-count').innerText()).includes('2 selected'));
await page.evaluate(() => { window.fixtureBlockApproval = true; });
await frame.locator('#review-prepare').click();
await frame.getByRole('heading', { name: 'Approval preparation needs attention', exact: true }).waitFor();
check('Oversized approval displays the complete-manifest block', (await frame.locator('#review-prepared').innerText()).includes('complete approval manifest is too large') && (await frame.locator('#review-ready-count').innerText()).includes('2 selected'));
check('Blocked approval has no final-request action', await frame.getByRole('button', { name: 'Request final approval in conversation', exact: true }).count() === 0);
await page.evaluate(() => { window.fixtureBlockApproval = false; });
await frame.locator('#review-prepare').click();
await frame.getByRole('heading', { name: 'Prepared for final approval', exact: true }).waitFor();
check('Only selected rows prepare', (await frame.locator('#review-prepared').innerText()).includes('2 exact changes'));
await frame.getByRole('button', { name: 'Request final approval in conversation', exact: true }).click();
await page.waitForFunction(() => window.fixtureMessage?.content?.[0]?.text?.includes('trusted final exact-action'));
check('Conversation request does not claim approval', (await page.evaluate(() => window.fixtureMessage)).content[0].text.includes('not approval'));
check('Server exact approval manifest is attached', (await page.evaluate(() => window.fixtureContext)).content[0].text.includes('pricing_review_apply'));
check('No apply or catalog writes from UI', !(await page.evaluate(() => window.fixtureCalls)).some(call => /apply|products_update|pricing_rules_save/.test(call.name)));
await page.screenshot({ path: `${directory}/pricing-review-approval.png`, fullPage: false });
await frame.locator('#review-heading').scrollIntoViewIfNeeded();
await page.screenshot({ path: `${directory}/pricing-review-desktop.png`, fullPage: false });
await row('B').getByRole('button', { name: 'Modify / instruct', exact: true }).click();
await frame.locator('#review-edit-value').fill('25.50');
await frame.locator('#review-edit-note').fill('Batch correction required.');
await frame.getByRole('button', { name: 'Save revision request', exact: true }).click();
await row('B').getByText('Needs revision', { exact: true }).waitFor();
check('Changing a decision invalidates prepared approval', await frame.locator('#review-prepared').innerText() === '');
await batchCheck(['B', 'D']);
await frame.locator('#review-revise').click();
await frame.locator('#review-edit-value').fill('25.50');
await frame.locator('#review-edit-note').fill('Set both fixture amounts to the reviewed full-sheet value.');
await frame.getByRole('button', { name: 'Save revision request', exact: true }).click();
await frame.locator('#review-edit-form').waitFor({ state: 'hidden' });
check('Batch modification reaches every selected line', (await row('B').innerText()).includes('25.50') && (await row('D').innerText()).includes('25.50'));
await batchCheck(['B', 'D']);
await frame.locator('#review-recalculate').click();
await row('B').getByText('Pending review', { exact: true }).waitFor();
await batchCheck(['B', 'D']);
await frame.locator('#review-reject').click();
await row('B').getByText('Rejected', { exact: true }).waitFor();
check('Batch rejection preserves line visibility', await frame.locator('.review-table > tbody > tr').count() === 6 && (await row('D').innerText()).includes('Rejected'));
await row('E').getByRole('button', { name: 'Reset to pending', exact: true }).click();
await row('E').getByText('Pending review', { exact: true }).waitFor();
check('Rejected line can be reopened', (await frame.locator('#review-progress').innerText()).includes('2 lines still need'));
await row('B').getByRole('button', { name: 'Modify / instruct', exact: true }).click();
await frame.locator('#review-edit-clear').check();
await frame.getByRole('button', { name: 'Save revision request', exact: true }).click();
await row('B').getByText('Needs revision', { exact: true }).waitFor();
await row('B').getByRole('button', { name: 'Recalculate', exact: true }).click();
await row('B').getByText('Pending review', { exact: true }).waitFor();
check('Manual amount can return to source calculation', !(await row('B').innerText()).includes('Requested revision') && (await row('B').innerText()).includes('25.20'));
await row('B').getByRole('button', { name: 'Reject', exact: true }).click();
await row('B').getByText('Rejected', { exact: true }).waitFor();
await frame.locator('#review-prepare').click();
await frame.getByRole('heading', { name: 'Prepared for final approval', exact: true }).waitFor();
await page.evaluate(() => window.fixtureCompletePrepared());
await frame.locator('#review-refresh').click();
await row('A').getByText('verified', { exact: true }).waitFor();
check('Execution readback status is visible and locked', await row('A').getByRole('button', { name: 'Modify / instruct', exact: true }).isDisabled());
await page.setViewportSize({ width: 390, height: 844 });
await frame.locator('#review-workspace').scrollIntoViewIfNeeded();
await page.screenshot({ path: `${directory}/pricing-review-mobile.png`, fullPage: false });
check('Mobile document does not overflow horizontally', await frame.locator('body').evaluate(node => node.scrollWidth <= node.clientWidth + 1));
console.log(JSON.stringify({ consoleErrors: errors }));
check('No frontend runtime errors', errors.filter(message => !message.includes('favicon.ico')).length === 0);
await writeFile(`${directory}/pricing-workspace-ui-results.json`, JSON.stringify({ url: page.url(), browser: process.env.PLAYWRIGHT_CHANNEL ?? 'Playwright Chromium', viewports: ['1440x1100', '390x844'], checks: results, errors, toolCalls: await page.evaluate(() => window.fixtureCalls) }, null, 2));
console.log(JSON.stringify({ checks: results.length, passed: results.every(item => item.passed), errors }));
} finally { await browser.close(); }
